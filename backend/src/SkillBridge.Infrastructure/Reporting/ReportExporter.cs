using System.Text;
using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SkillBridge.Application.Common.Interfaces;
using SkillBridge.Application.DTOs;

namespace SkillBridge.Infrastructure.Reporting;

public class ReportExporter : IReportExporter
{
    static ReportExporter()
    {
        QuestPDF.Settings.License = LicenseType.Community;
    }

    public byte[] ExportSkillGapCsv(IEnumerable<EmployeeSkillGapRowDto> rows)
    {
        var sb = new StringBuilder();
        sb.AppendLine("EmployeeName,SkillName,CurrentLevel,RequiredLevel,GapStatus,RecommendedAction");
        foreach (var row in rows)
        {
            sb.AppendLine(string.Join(",",
                EscapeCsv(row.EmployeeName),
                EscapeCsv(row.SkillName),
                row.CurrentLevel?.ToString() ?? "",
                row.RequiredLevel?.ToString() ?? "",
                EscapeCsv(row.GapLabel),
                EscapeCsv(row.RecommendedAction)));
        }
        return Encoding.UTF8.GetBytes(sb.ToString());
    }

    public byte[] ExportSummaryCsv(
        string reportTitle,
        IEnumerable<(string Col1, string Col2, string Col3, string Col4)> rows,
        string[] headers)
    {
        var sb = new StringBuilder();
        sb.AppendLine($"# {EscapeCsv(reportTitle)}");
        sb.AppendLine(string.Join(",", headers.Select(EscapeCsv)));
        foreach (var r in rows)
        {
            sb.AppendLine(string.Join(",", EscapeCsv(r.Col1), EscapeCsv(r.Col2), EscapeCsv(r.Col3), EscapeCsv(r.Col4)));
        }
        return Encoding.UTF8.GetBytes(sb.ToString());
    }

    public byte[] ExportSummaryPdf(
        string reportTitle,
        string departmentName,
        string generatedBy,
        IEnumerable<(string Col1, string Col2, string Col3, string Col4)> rows,
        string[] headers)
    {
        var rowList = rows.ToList();

        return Document.Create(container =>
        {
            container.Page(page =>
            {
                page.Size(PageSizes.A4);
                page.Margin(36);
                page.PageColor(Colors.White);
                page.DefaultTextStyle(x => x.FontSize(10).FontColor("#0F2744"));

                page.Header().Column(col =>
                {
                    col.Item().Text("SkillBridge AI — Workforce Analytics Report").FontSize(18).Bold().FontColor("#0F2744");
                    col.Item().PaddingTop(4).Text(reportTitle).FontSize(12).SemiBold().FontColor("#32936F");
                    col.Item().PaddingTop(2).Text($"Department: {departmentName}   |   Generated by: {generatedBy}   |   {DateTime.UtcNow:yyyy-MM-dd HH:mm} UTC")
                        .FontSize(9).FontColor("#475569");
                    col.Item().PaddingVertical(8).LineHorizontal(1).LineColor("#E2E8F0");
                });

                page.Content().Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.RelativeColumn(2);
                        columns.RelativeColumn(2);
                        columns.RelativeColumn(1.5f);
                        columns.RelativeColumn(3);
                    });

                    table.Header(header =>
                    {
                        foreach (var h in headers.Take(4))
                        {
                            header.Cell().Background("#E3F3EA").Padding(6).Text(h).Bold().FontSize(9);
                        }
                    });

                    foreach (var row in rowList)
                    {
                        table.Cell().BorderBottom(1).BorderColor("#F1F5F9").Padding(6).Text(row.Col1);
                        table.Cell().BorderBottom(1).BorderColor("#F1F5F9").Padding(6).Text(row.Col2);
                        table.Cell().BorderBottom(1).BorderColor("#F1F5F9").Padding(6).Text(row.Col3);
                        table.Cell().BorderBottom(1).BorderColor("#F1F5F9").Padding(6).Text(row.Col4);
                    }
                });

                page.Footer().AlignRight().Text(x =>
                {
                    x.Span("SkillBridge AI · Page ");
                    x.CurrentPageNumber();
                    x.Span(" of ");
                    x.TotalPages();
                });
            });
        }).GeneratePdf();
    }

    private static string EscapeCsv(string? value)
    {
        if (string.IsNullOrEmpty(value)) return "";
        if (value.Contains(',') || value.Contains('"') || value.Contains('\n'))
        {
            return $"\"{value.Replace("\"", "\"\"")}\"";
        }
        return value;
    }
}
